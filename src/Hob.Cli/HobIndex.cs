using System.Text;

namespace Hob.Cli;

/// <summary>
/// <c>index.txt</c>: every spelling the shell wrappers may handle without starting this exe, already resolved.
/// One <c>kind|key|value</c> line each, because cmd and bash can split that with builtins. Keys are lower-case.
/// A wrapper that finds no line for what you typed hands the words to the exe, so only definite hits live here
/// and every error message comes from one place. docs/how-it-works.md lists the kinds.
/// </summary>
internal static class HobIndex
{
    /// <summary>The wrappers compare this prefix to decide whether they can read the file at all.</summary>
    public const string FormatHeader = "# hob index 2";

    public static string Header(HobPaths paths)
    {
        long exe = File.Exists(paths.ExePath) ? File.GetLastWriteTimeUtc(paths.ExePath).Ticks : 0;
        return $"{FormatHeader} {exe}. Generated by hob-cli.exe; do not edit.";
    }

    /// <summary>The same rule the PowerShell and bash wrappers apply: nothing it was built from is newer than it.</summary>
    public static bool IsCurrent(Model model)
    {
        var paths = model.Paths;
        if (!File.Exists(paths.IndexFile)) return false;
        using (var reader = new StreamReader(paths.IndexFile))
        {
            if (reader.ReadLine() != Header(paths)) return false;
        }
        var built = File.GetLastWriteTimeUtc(paths.IndexFile);
        foreach (string path in model.Watch)
        {
            if (File.Exists(path) && File.GetLastWriteTimeUtc(path) > built) return false;
            if (Directory.Exists(path) && Directory.GetLastWriteTimeUtc(path) > built) return false;
        }
        return true;
    }

    public static string Render(Model model)
    {
        var lines = new List<string> { Header(model.Paths) };
        var seen = new HashSet<string>();
        void Add(string kind, string key, string value, string? extra = null)
        {
            if (!seen.Add($"{kind}|{key}")) return;
            lines.Add(extra is null ? $"{kind}|{key}|{value}" : $"{kind}|{key}|{value}|{extra}");
        }

        foreach (var place in model.Places)
        {
            foreach (string key in Matcher.Prefixes(place.Name))
            {
                if (Matcher.FindPlace(model, [key]).Entry is { } found) Add("to", key, found.Path);
            }
        }
        foreach (var plugin in model.Plugins)
        {
            foreach (string pluginKey in Matcher.Prefixes(plugin.Name))
            {
                if (Matcher.Find(model.Plugins, pluginKey).Entry == plugin)
                {
                    foreach (var location in plugin.Locations)
                    {
                        foreach (string key in Matcher.Prefixes(location.Name))
                        {
                            if (Matcher.FindPlace(model, [pluginKey, key]).Entry is { } found) Add("to", $"{pluginKey} {key}", found.Path);
                        }
                    }
                }

                if (Matcher.Find(model.Top, pluginKey).Entry != plugin) continue;
                if (plugin.Root is not null) Add("go", pluginKey, plugin.Root);
                foreach (var child in plugin.Children)
                {
                    foreach (string key in Matcher.Prefixes(child.Name))
                    {
                        switch (Matcher.Find(plugin.Children, key).Entry)
                        {
                            case Place location: Add("go", $"{pluginKey} {key}", location.Path); break;
                            case PluginCommand { Run.Count: 1 } command: Add("run", $"{pluginKey} {key}", command.Run[0], plugin.Dir); break;
                        }
                    }
                }
            }
        }

        foreach (var builtin in Model.Builtins) lines.Add($"top|{builtin.Name}|{Clean(builtin.Description)}");
        foreach (var plugin in model.Plugins)
        {
            lines.Add($"top|{plugin.Name}|{Clean(plugin.Description)}");
            foreach (var place in plugin.Locations) lines.Add($"sub|{plugin.Name}|{place.Name}|place|{place.Path}");
            foreach (var command in plugin.Commands) lines.Add($"sub|{plugin.Name}|{command.Name}|command|{Clean(command.Description)}");
        }
        foreach (var place in model.Places) lines.Add($"tocomp|{place.Completion}|{place.Path}");
        foreach (string path in model.Watch.Append(model.Paths.ExePath)) lines.Add($"watch|{path}|");
        return string.Join("\n", lines) + "\n";
    }

    private static string Clean(string text) => text.Replace('|', '/').Replace('\r', ' ').Replace('\n', ' ');

    /// <summary>
    /// Rewrites the index and the PATH commands when anything they come from changed. Written in place rather
    /// than renamed over, so the data folder's own timestamp, which can be on the watch list, does not move.
    /// </summary>
    public static bool Refresh(Model model, TextWriter err, bool force = false)
    {
        if (!force && IsCurrent(model)) return false;
        foreach (string warning in model.Warnings) err.WriteLine($"hob: {warning}");
        foreach (string warning in Bin.Write(model)) err.WriteLine($"hob: {warning}");
        Directory.CreateDirectory(model.Paths.DataDir);
        File.WriteAllText(model.Paths.IndexFile, Render(model), new UTF8Encoding(false));
        return true;
    }
}
