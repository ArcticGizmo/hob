    /// <summary>Writes the commands and removes ones for plugins that are gone. Returns warnings.</summary>
    public static List<string> Write(Model model)
    {
        var warnings = new List<string>();
        var names = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase) { ["hob"] = "" };
        string alias = model.Settings.Alias;
        if (alias.Length > 0 && !names.ContainsKey(alias))
        {
            if (IsTaken(alias, model.Paths.BinDir)) warnings.Add($"no '{alias}' short name, because it would hide an existing command");
            else names[alias] = "";
        }
        if (model.Settings.Shortcuts)
        {
            foreach (var plugin in model.Plugins)
            {
                if (names.ContainsKey(plugin.Name)) continue;
                if (IsTaken(plugin.Name, model.Paths.BinDir)) warnings.Add($"no '{plugin.Name}' shortcut, because it would hide an existing command");
                else names[plugin.Name] = plugin.Name;
            }
        }

        var keep = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (name, prefix) in names) keep.UnionWith(Shims.Write(model.Paths, name, prefix));

        foreach (string file in Directory.GetFiles(model.Paths.BinDir))
        {
            if (keep.Contains(Path.GetFileName(file))) continue;
            if (Head(file).Contains(Shims.Marker)) File.Delete(file);
        }
        return warnings;
    }

    private static string Head(string file)
    {
        using var reader = new StreamReader(file);
        var buffer = new char[400];
        return new string(buffer, 0, reader.Read(buffer, 0, buffer.Length));
    }

    public static bool IsTaken(string name, string binDir)
    {
        if (CmdInternal.Contains(name) || PowerShellNames.Contains(name)) return true;
        string bin = Path.TrimEndingDirectorySeparator(Path.GetFullPath(binDir));
        var extensions = new[] { "" }.Concat((Environment.GetEnvironmentVariable("PATHEXT") ?? ".COM;.EXE;.BAT;.CMD").Split(';', StringSplitOptions.RemoveEmptyEntries)).Append(".ps1");
        foreach (string raw in (Environment.GetEnvironmentVariable("PATH") ?? "").Split(';', StringSplitOptions.RemoveEmptyEntries))
        {
            string dir;
            try { dir = Path.TrimEndingDirectorySeparator(Path.GetFullPath(raw.Trim('"'))); }
            catch (Exception ex) when (ex is ArgumentException or NotSupportedException or PathTooLongException) { continue; }
            if (dir.Equals(bin, StringComparison.OrdinalIgnoreCase)) continue;
            if (extensions.Any(ext => File.Exists(Path.Combine(dir, name + ext)))) return true;
        }
        return false;
    }
}
